const showplanStateSQL = "SELECT CAST(431205 AS int) AS chen_showplan_state_probe, @@TRANCOUNT AS chen_trancount, XACT_STATE() AS chen_xact_state, @@OPTIONS & 2 AS chen_implicit"
const showplanOnSQL = "SET SHOWPLAN_XML ON"
const showplanOffSQL = "SET SHOWPLAN_XML OFF"

type showplanState struct{ count, state, implicit int }

func probeShowplan(ctx context.Context, c *console) (showplanState, error) {
	rows, err := c.conn.QueryContext(ctx, showplanStateSQL)
	if err != nil {
		return showplanState{}, err
	}
	defer rows.Close()
	columns, err := rows.Columns()
	if err != nil || len(columns) != 4 || columns[0] != "chen_showplan_state_probe" {
		return showplanState{}, &APIError{"plan_session_state_unknown", "SHOWPLAN must initially be OFF; reconnect or turn it off before requesting a plan"}
	}
	var marker int
	var state showplanState
	if !rows.Next() {
		return state, &APIError{"plan_session_state_unknown", "Cannot verify SHOWPLAN session state"}
	}
	if err = rows.Scan(&marker, &state.count, &state.state, &state.implicit); err != nil {
		return state, err
	}
	if marker != 431205 || rows.Next() || rows.NextResultSet() {
		return state, &APIError{"plan_session_state_unknown", "Cannot verify SHOWPLAN session state"}
	}
	return state, rows.Err()
}

func (v *Server) runSQLServerPlan(s *session, c *console, e *execution, command, version string) (err error) {
	initial, err := probeShowplan(e.ctx, c)
	if err != nil {
		return err
	}
	if initial.state < 0 || initial.count == 0 && initial.implicit != 0 {
		return &APIError{"plan_transaction_unknown", "Use a committable transaction or an idle connection with implicit transactions disabled"}
	}
	var permission sql.NullInt64
	if err = c.conn.QueryRowContext(e.ctx, "SELECT HAS_PERMS_BY_NAME(DB_NAME(), 'DATABASE', 'SHOWPLAN')").Scan(&permission); err != nil {
		return err
	}
	if !permission.Valid || permission.Int64 != 1 {
		return &APIError{"plan_permission_denied", "SHOWPLAN permission is required in every referenced database"}
	}
	p := emptyPlan(s.grant.Config.Dialect)
	p.ServerVersion = planString(version)
	reserved := 0
	// OFF is attempted even when ON's acknowledgement was lost. A failed recovery
	// discards the console; subsequent user SQL must never run under SHOWPLAN.
	defer func() {
		if e.cancelRequested.Load() {
			<-e.cancelDone
		}
		cleanup, stop := context.WithTimeout(context.Background(), 3*time.Second)
		defer stop()
		_, restoreErr := c.conn.ExecContext(cleanup, showplanOffSQL)
		if restoreErr == nil {
			var restored showplanState
			restored, restoreErr = probeShowplan(cleanup, c)
			if restoreErr == nil && restored != initial {
				restoreErr = errors.New("transaction changed during SHOWPLAN")
			}
		}
		if restoreErr != nil {
			invalidateEditConnection(s, c)
			p.Effects = PlanEffects{"UNKNOWN", "UNKNOWN", "UNKNOWN", "DISCARD"}
			err = &APIError{"plan_connection_lost", "SHOWPLAN recovery or transaction state could not be verified; reconnect before continuing"}
		} else if p != nil {
			p.Effects = PlanEffects{"RESTORED", "UNCHANGED", "NONE", "REUSE"}
		}
		if p != nil {
			v.reservePlan(s, p, reserved)
			e.mu.Lock()
			e.planResult = p
			e.mu.Unlock()
		}
	}()
	if _, err = c.conn.ExecContext(e.ctx, showplanOnSQL); err != nil {
		return err
	}
	rows, err := c.conn.QueryContext(e.ctx, command)
	if err != nil {
		return err
	}
	result, readErr := v.readRows(s, rows)
	extra := rows.NextResultSet()
	rowsErr := rows.Err()
	closeErr := rows.Close()
	if readErr != nil {
		return readErr
	}
	if rowsErr != nil {
		return rowsErr
	}
	if closeErr != nil {
		return closeErr
	}
	reserved = result.memoryBytes
	p = normalizePlan("sqlserver", result, version)
	if extra {
		p.Roots = []*PlanNode{}
		p.Status = "RAW_ONLY"
		p.Capabilities.Structured = false
		p.Capabilities.Hierarchy = false
		p.warn("plan_extra_results", "Multiple SHOWPLAN documents are available only as raw output")
	}
	return nil
}

var oraclePlanCommand = regexp.MustCompile(`(?s)^EXPLAIN PLAN SET STATEMENT_ID = '(chen_[a-f0-9]{20})' INTO ("(?:[^"]|"")+"\."(?:[^"]|"")+") FOR `)
var db2PlanCommand = regexp.MustCompile(`(?s)^EXPLAIN PLAN SET QUERYNO = 1 SET QUERYTAG = '(chen_[a-f0-9]{15})' FOR `)

func specialPlanDialect(d string) bool {
	return d == "oracle" || d == "sqlserver" || d == "db2" || d == "dameng" || d == "oceanbase-oracle"
}

// All operational SQL is enumerated before authorization and audit. Identifiers
// and tags here are generated by this server, never accepted from an HTTP input.
func planAuthorizationSQL(d, command string) []string {
	if d == "sqlserver" {
		return []string{showplanStateSQL, "SELECT HAS_PERMS_BY_NAME(DB_NAME(), 'DATABASE', 'SHOWPLAN')", showplanOnSQL, command, showplanOffSQL}
	}
	if d == "oracle" {
		m := oraclePlanCommand.FindStringSubmatch(command)
		if len(m) != 3 {
			return []string{command}
		}
		savepoint := "chen_plan_" + strings.TrimPrefix(m[1], "chen_")
		return []string{command, oraclePlanReadSQL(m[2], m[1]), "BEGIN", "SAVEPOINT " + savepoint, "ROLLBACK TO " + savepoint, "ROLLBACK"}
	}
	if d == "db2" {
		// The schema is selected from a bounded inventory in estimatedPlanSQL and
		// encoded as a server-owned marker after the generated command's final line.
		main, schema, tag, ok := db2PlanParts(command)
		if !ok {
			return []string{command}
		}
		savepoint := "chen_plan_" + strings.TrimPrefix(tag, "chen_")
		commands := []string{main, db2PlanReadSQL(schema, tag), "BEGIN", "SAVEPOINT " + savepoint + " ON ROLLBACK RETAIN CURSORS", "ROLLBACK TO SAVEPOINT " + savepoint, "RELEASE SAVEPOINT " + savepoint, "ROLLBACK"}
		return append(commands, db2PlanExtraSQL(schema, tag)...)
	}
	return []string{command}
}

const db2PlanMarker = "\n-- chen-explain-schema: "

func db2PlanParts(command string) (string, string, string, bool) {
	i := strings.LastIndex(command, db2PlanMarker)
	if i < 0 {
		return "", "", "", false
	}
	main := command[:i]
	schemaBytes, err := hex.DecodeString(command[i+len(db2PlanMarker):])
	if err != nil {
		return "", "", "", false
	}
	schema := string(schemaBytes)
	m := db2PlanCommand.FindStringSubmatch(main)
	if len(m) != 2 || schema == "" || strings.ContainsAny(schema, "\r\n") {
		return "", "", "", false
	}
	return main, schema, m[1], true
}
func oraclePlanReadSQL(table, tag string) string {
	return `SELECT * FROM ` + table + ` WHERE STATEMENT_ID='` + tag + `' ORDER BY ID,POSITION`
}

var db2PlanKey = []string{"EXPLAIN_REQUESTER", "EXPLAIN_TIME", "SOURCE_NAME", "SOURCE_SCHEMA", "SOURCE_VERSION", "EXPLAIN_LEVEL", "STMTNO", "SECTNO"}

func db2PlanReadSQL(schema, tag string) string {
	table := quoteDatabaseIdentifier(schema, "db2") + "."
	joins := []string{}
	streams := []string{}
	for _, k := range db2PlanKey {
		joins = append(joins, "st."+k+"=o."+k)
		streams = append(streams, "s."+k+"=o."+k)
	}
	return `SELECT o.OPERATOR_ID,o.OPERATOR_TYPE,o.TOTAL_COST,s.TARGET_ID AS PARENT_ID,s.STREAM_COUNT AS ESTIMATED_ROWS FROM ` + table + `EXPLAIN_OPERATOR o JOIN ` + table + `EXPLAIN_STATEMENT st ON ` + strings.Join(joins, " AND ") + ` LEFT JOIN ` + table + `EXPLAIN_STREAM s ON ` + strings.Join(streams, " AND ") + ` AND s.SOURCE_TYPE='O' AND s.SOURCE_ID=o.OPERATOR_ID AND s.TARGET_TYPE='O' WHERE st.EXPLAIN_REQUESTER=CURRENT USER AND st.QUERYNO=1 AND RTRIM(st.QUERYTAG)='` + tag + `' ORDER BY o.OPERATOR_ID,s.STREAM_ID`
}

func (v *Server) runAuxiliaryPlan(s *session, c *console, e *execution, command, version string) (err error) {
	d := s.grant.Config.Dialect
	var read, tag string
	var extraQueries []string
	if d == "oracle" {
		m := oraclePlanCommand.FindStringSubmatch(command)
		if len(m) != 3 {
			return &APIError{"plan_prerequisites_unmet", "Invalid generated Oracle plan identity"}
		}
		tag = m[1]
		read = oraclePlanReadSQL(m[2], tag)
	} else {
		main, schema, t, ok := db2PlanParts(command)
		if !ok {
			return &APIError{"plan_prerequisites_unmet", "Invalid generated DB2 plan identity"}
		}
		command = main
		tag = t
		read = db2PlanReadSQL(schema, tag)
		extraQueries = db2PlanExtraSQL(schema, tag)
	}
	state, probeErr := planAuxTransactionState(e.ctx, c, d)
	if probeErr != nil {
		return probeErr
	}
	if state != editTxIdle && state != editTxActive {
		return &APIError{"plan_transaction_unknown", "Cannot safely isolate plan-table changes in the current transaction"}
	}
	// Idle connections use a transaction wholly owned by this request. Active
	// user transactions retain ownership and only this savepoint is rolled back.
	boundary := &editBoundary{conn: c.conn, dialect: d, savepoint: "chen_plan_" + strings.TrimPrefix(tag, "chen_")}
	if state == editTxIdle {
		boundary.tx, err = c.conn.BeginTx(context.WithoutCancel(e.ctx), nil)
	} else {
		if err = boundary.preserveOracleTransaction(); err != nil {
			return err
		}
		q := "SAVEPOINT " + boundary.savepoint
		if d == "db2" {
			q += " ON ROLLBACK RETAIN CURSORS"
		}
		_, err = c.conn.ExecContext(e.ctx, q)
	}
	if err != nil {
		boundary.restoreOracleTransaction()
		return err
	}
	p := emptyPlan(s.grant.Config.Dialect)
	p.ServerVersion = planString(version)
	reserved := 0
	defer func() {
		if e.cancelRequested.Load() {
			<-e.cancelDone
		}
		cleanup, stop := context.WithTimeout(context.Background(), 3*time.Second)
		defer stop()
		if cleanupErr := boundary.rollback(cleanup); cleanupErr != nil {
			invalidateEditConnection(s, c)
			p.Effects = PlanEffects{"UNKNOWN", "UNKNOWN", "UNKNOWN", "DISCARD"}
			err = &APIError{"plan_connection_lost", "Plan-table rollback failed; reconnect before continuing"}
		} else if p != nil {
			p.Effects = PlanEffects{"UNCHANGED", "UNCHANGED", "CLEANED", "REUSE"}
			if state == editTxActive {
				p.Effects.TransactionState = "PARTICIPATED"
			}
		}
		if p != nil {
			v.reservePlan(s, p, reserved)
			e.mu.Lock()
			e.planResult = p
			e.mu.Unlock()
		}
	}()
	if _, err = boundary.exec(e.ctx, command); err != nil {
		return err
	}
	var rows *sql.Rows
	if boundary.tx != nil {
		rows, err = boundary.tx.QueryContext(e.ctx, read)
	} else {
		rows, err = c.conn.QueryContext(e.ctx, read)
	}
	if err != nil {
		return err
	}
	result, readErr := v.readRows(s, rows)
	rowsErr := rows.Err()
	closeErr := rows.Close()
	if readErr != nil {
		return readErr
	}
	if rowsErr != nil {
		return rowsErr
	}
	if closeErr != nil {
		return closeErr
	}
	reserved = result.memoryBytes
	p = normalizePlan(d, result, version)
	if d == "db2" {
		captures := map[string]*Result{}
		for i, query := range extraQueries {
			var extraRows *sql.Rows
			if boundary.tx != nil {
				extraRows, err = boundary.tx.QueryContext(e.ctx, query)
			} else {
				extraRows, err = c.conn.QueryContext(e.ctx, query)
			}
			if err != nil {
				return err
			}
			capture, readErr := v.readRows(s, extraRows)
			rowsErr := extraRows.Err()
			closeErr := extraRows.Close()
			if readErr != nil {
				return readErr
			}
			if rowsErr != nil {
				return rowsErr
			}
			if closeErr != nil {
				return closeErr
			}
			reserved += capture.memoryBytes
			captures[db2CaptureTables[i]] = capture
		}
		enrichDB2Plan(p, captures)
	}
	return nil
}

var db2CaptureTables = []string{"EXPLAIN_INSTANCE", "EXPLAIN_STATEMENT", "EXPLAIN_OPERATOR", "EXPLAIN_STREAM", "EXPLAIN_OBJECT", "EXPLAIN_PREDICATE", "EXPLAIN_ARGUMENT", "EXPLAIN_DIAGNOSTIC", "EXPLAIN_DIAGNOSTIC_DATA"}

func db2PlanExtraSQL(schema, tag string) []string {
	out := []string{}
	prefix := quoteDatabaseIdentifier(schema, "db2") + "."
	for _, table := range db2CaptureTables {
		keys := db2PlanKey
		if table == "EXPLAIN_INSTANCE" {
			keys = keys[:5]
		}
		terms := []string{}
		for _, k := range keys {
			terms = append(terms, "st."+k+"=t."+k)
		}
		out = append(out, "SELECT t.* FROM "+prefix+table+" t WHERE EXISTS (SELECT 1 FROM "+prefix+"EXPLAIN_STATEMENT st WHERE "+strings.Join(terms, " AND ")+" AND st.EXPLAIN_REQUESTER=CURRENT USER AND st.QUERYNO=1 AND RTRIM(st.QUERYTAG)='"+tag+"')")
	}
	return out
}
func enrichDB2Plan(p *ExecutionPlan, captures map[string]*Result) {
	tables := map[string]any{}
	complete := !p.RawTruncated
	for name, r := range captures {
		tables[name] = map[string]any{"columns": r.Columns, "rows": r.Rows}
		if r.Truncated {
			complete = false
		}
		for _, row := range r.masked {
			for _, masked := range row {
				if masked {
					complete = false
				}
			}
		}
	}
	raw, _ := json.Marshal(map[string]any{"resultSets": tables})
	p.RawText = planPrefix(string(raw), planMaxBytes)
	p.Capabilities.Raw = len(raw) > 0
	if len(raw) > planMaxBytes {
		p.RawTruncated = true
		complete = false
	}
	if !complete {
		p.Status = "RAW_ONLY"
		p.Roots = []*PlanNode{}
		p.Capabilities.Structured = false
		p.Capabilities.Hierarchy = false
		p.Capabilities.Predicates = false
		p.warn("plan_incomplete_capture", "Native Db2 plan tables were masked or truncated; inspect raw output")
		return
	}
	roots, parseErr := parseDB2Captured(captures)
	if parseErr != nil {
		p.Status = "RAW_ONLY"
		p.Roots = []*PlanNode{}
		p.Capabilities.Structured = false
		p.Capabilities.Hierarchy = false
		p.warn("plan_parse_failed", parseErr.Error())
		return
	}
	p.Roots = roots
	p.Status = "SUCCESS"
	p.Capabilities.Structured = true
	p.Capabilities.Hierarchy = true
	p.Capabilities.Cost = false
	p.Capabilities.EstimatedRows = false
	nodes := map[string][]*PlanNode{}
	var visit func([]*PlanNode)
	visit = func(ns []*PlanNode) {
		for _, n := range ns {
			if n.NativeID != nil {
				nodes[*n.NativeID] = append(nodes[*n.NativeID], n)
				p.Capabilities.Cost = p.Capabilities.Cost || n.Cost != nil
				p.Capabilities.EstimatedRows = p.Capabilities.EstimatedRows || n.Rows != nil
			}
			visit(n.Children)
		}
	}
	visit(p.Roots)
	for name, r := range captures {
		columns, err := planColumnIndex(r)
		if err != nil {
			continue
		}
		for _, row := range r.Rows {
			value := func(k string) string {
				if i, ok := columns[k]; ok {
					return planText(row[i])
				}
				return ""
			}
			switch name {
			case "EXPLAIN_PREDICATE":
				for _, n := range nodes[value("OPERATOR_ID")] {
					if value("PREDICATE_TEXT") == "" {
						continue
					}
					n.Predicates["predicate "+value("PREDICATE_ID")] = value("PREDICATE_TEXT")
					p.Capabilities.Predicates = true
				}
			case "EXPLAIN_ARGUMENT":
				for _, n := range nodes[value("OPERATOR_ID")] {
					key := "argument " + value("ARGUMENT_TYPE")
					v := value("ARGUMENT_VALUE")
					if old := n.Attributes[key]; old != "" {
						v = old + "; " + v
					}
					n.Attributes[key] = v
				}
			case "EXPLAIN_STREAM":
				if value("OBJECT_NAME") != "" {
					id := value("TARGET_ID")
					if value("TARGET_TYPE") != "O" {
						id = value("SOURCE_ID")
					}
					for _, n := range nodes[id] {
						n.Table = planString(value("OBJECT_NAME"))
						relation := value("OBJECT_NAME")
						if schema := value("OBJECT_SCHEMA"); schema != "" {
							relation = schema + "." + relation
						}
						n.Relation = planString(relation)
					}
				}
			}
		}
	}
}

func planAuxTransactionState(ctx context.Context, c *console, d string) (editTxState, error) {
	return editTransactionState(ctx, c, d)
}

func resolveOraclePlanTable(ctx context.Context, c *console) (string, error) {
	var owner string
	if err := c.conn.QueryRowContext(ctx, "SELECT SYS_CONTEXT('USERENV','CURRENT_SCHEMA') FROM DUAL").Scan(&owner); err != nil {
		return "", err
	}
	name := "PLAN_TABLE"
	seen := map[string]bool{}
	for depth := 0; depth < 8; depth++ {
		key := owner + "\x00" + name
		if seen[key] {
			break
		}
		seen[key] = true
		var kind string
		err := c.conn.QueryRowContext(ctx, "SELECT OBJECT_TYPE FROM ALL_OBJECTS WHERE OWNER=:1 AND OBJECT_NAME=:2 AND OBJECT_TYPE IN ('TABLE','VIEW','SYNONYM','MATERIALIZED VIEW')", owner, name).Scan(&kind)
		if err != nil && !errors.Is(err, sql.ErrNoRows) {
			return "", err
		}
		if kind == "TABLE" {
			table := quoteDatabaseIdentifier(owner, "oracle") + "." + quoteDatabaseIdentifier(name, "oracle")
			var triggers int
			if err = c.conn.QueryRowContext(ctx, "SELECT COUNT(*) FROM ALL_TRIGGERS WHERE TABLE_OWNER=:1 AND TABLE_NAME=:2 AND STATUS='ENABLED'", owner, name).Scan(&triggers); err != nil {
				return "", err
			}
			if triggers != 0 {
				return "", &APIError{"plan_prerequisites_unmet", "PLAN_TABLE with enabled triggers is not supported"}
			}
			rows, err := c.conn.QueryContext(ctx, "SELECT COLUMN_NAME,DATA_TYPE FROM ALL_TAB_COLUMNS WHERE OWNER=:1 AND TABLE_NAME=:2", owner, name)
			if err != nil {
				return "", err
			}
			cols := map[string]string{}
			for rows.Next() {
				var n, t string
				if err = rows.Scan(&n, &t); err != nil {
					rows.Close()
					return "", err
				}
				cols[n] = t
			}
			err = rows.Err()
			rows.Close()
			if err != nil {
				return "", err
			}
			for _, n := range []string{"STATEMENT_ID", "ID", "PARENT_ID", "OPERATION", "COST", "CARDINALITY", "POSITION"} {
				if cols[n] == "" {
					return "", &APIError{"plan_prerequisites_unmet", "PLAN_TABLE has incompatible columns"}
				}
			}
			return table, nil
		}
		if kind != "" && kind != "SYNONYM" {
			break
		}
		sourceOwner := owner
		if kind == "" && depth == 0 {
			sourceOwner = "PUBLIC"
		}
		var link sql.NullString
		err = c.conn.QueryRowContext(ctx, "SELECT TABLE_OWNER,TABLE_NAME,DB_LINK FROM ALL_SYNONYMS WHERE OWNER=:1 AND SYNONYM_NAME=:2", sourceOwner, name).Scan(&owner, &name, &link)
		if err != nil {
			if errors.Is(err, sql.ErrNoRows) {
				break
			}
			return "", err
		}
		if link.Valid && link.String != "" {
			break
		}
	}
	return "", &APIError{"plan_prerequisites_unmet", "A compatible local Oracle PLAN_TABLE or synonym is required; Chen does not create it automatically"}
}

func resolveDB2PlanSchema(ctx context.Context, c *console) (string, error) {
	var user, mode, snapshot string
	if err := c.conn.QueryRowContext(ctx, "VALUES (CURRENT USER, CURRENT EXPLAIN MODE, CURRENT EXPLAIN SNAPSHOT)").Scan(&user, &mode, &snapshot); err != nil {
		return "", err
	}
	if strings.TrimSpace(mode) != "NO" || strings.TrimSpace(snapshot) != "NO" {
		return "", &APIError{"plan_session_state_unknown", "CURRENT EXPLAIN MODE and SNAPSHOT must both be NO before requesting a plan"}
	}
	tables := []string{"EXPLAIN_INSTANCE", "EXPLAIN_STATEMENT", "EXPLAIN_OPERATOR", "EXPLAIN_STREAM", "EXPLAIN_OBJECT", "EXPLAIN_PREDICATE", "EXPLAIN_ARGUMENT", "EXPLAIN_DIAGNOSTIC", "EXPLAIN_DIAGNOSTIC_DATA"}
	for _, schema := range []string{strings.TrimSpace(user), "SYSTOOLS"} {
		rows, err := c.conn.QueryContext(ctx, "SELECT TABNAME,TYPE FROM SYSCAT.TABLES WHERE TABSCHEMA=? AND TABNAME LIKE 'EXPLAIN!_%' ESCAPE '!'", schema)
		if err != nil {
			return "", err
		}
		found := map[string]string{}
		for rows.Next() {
			var n, t string
			if err = rows.Scan(&n, &t); err != nil {
				rows.Close()
				return "", err
			}
			found[strings.TrimSpace(n)] = t
		}
		err = rows.Err()
		rows.Close()
		if err != nil {
			return "", err
		}
		count := 0
		for _, n := range tables {
			if found[n] != "" {
				count++
			}
		}
		if count == 0 {
			continue
		}
		if count != len(tables) {
			return "", &APIError{"plan_prerequisites_unmet", "DB2 Explain table set is incomplete; install or migrate it outside Chen"}
		}
		for _, n := range tables {
			if found[n] != "T" {
				return "", &APIError{"plan_prerequisites_unmet", "DB2 Explain objects must be ordinary tables"}
			}
		}
		// A custom trigger can have effects outside the rollback boundary.
		var triggers int
		if err = c.conn.QueryRowContext(ctx, "SELECT COUNT(*) FROM SYSCAT.TRIGGERS WHERE TABSCHEMA=? AND TABNAME LIKE 'EXPLAIN!_%' ESCAPE '!'", schema).Scan(&triggers); err != nil {
			return "", err
		}
		if triggers != 0 {
			return "", &APIError{"plan_prerequisites_unmet", "DB2 Explain tables with triggers are not supported"}
		}
		return schema, nil
	}
	return "", &APIError{"plan_prerequisites_unmet", "DB2 LUW Explain tables are required in the authorization schema or SYSTOOLS; Chen does not create them automatically"}
}
